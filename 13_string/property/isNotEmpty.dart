// .isNotEmpty

// What
// - It is a property of the String class in Dart.
// - It checks whether the string is not empty or not and returns a boolean value.

// Syntax
// variable.isNotEmpty;

// Example
void main() {
  String myString = "Hello";
  bool isNotEmpty = myString.isNotEmpty;

  print("String: $myString");
  print("Is Not Empty: $isNotEmpty");
}
