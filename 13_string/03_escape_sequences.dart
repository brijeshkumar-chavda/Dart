void main() {
  // \n: Newline
  print("Hello\nI am on new line");

  // \t: Horizontal tab
  print("Column1\tColumn2");
  print("Row1\t Value1");
  print("Row2\t Value2");

  // \: add backslash
  print("I am a backslash \\");

  // \': add single quote
  print("I am a single quote \'");

  // \": add double quote
  print("I am a double quote \"");

  // \r: carriage return
  print("I am a carriage\rreturn");

  // \b: backspace
  print("I am a b\backspace");

  // \f: add form feed (page break)
  print("Line1\fLine2");

  // \v: add vertical tab
  print("Line1\vLine2");

  // \u: add unicode
  print("I am a unicode \u00A9");
}
