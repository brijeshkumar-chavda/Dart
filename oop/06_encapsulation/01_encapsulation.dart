// Encapsulation

// What is the Library in dart?
// By default every dart file is a library.
// Library is a collection of classes and functions.
// A library can be imported in another dart file using the import keyword.

// What is encapsulation?
// Encapsulation is a way to hide the internal details of a class from the outside world.
// It is a way to control the access to the class members.
// It is a way to protect the class from being modified or accessed from outside the class.

// How to achieve encapsulation in dart?
// In dart, we can achieve encapsulation using the private which is done my pre-fixing the variable name with _ (underscore).
// Providing public getter and setter methods to access and update the value of private property.

// NOTE
// Note: Dart doesn’t support keywords like public, private, and protected. Dart uses _ (underscore) to make a property or method private. The encapsulation happens at library level, not at class level.
