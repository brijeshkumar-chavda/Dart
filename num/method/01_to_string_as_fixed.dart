// .toStringAsFixed()

// What
// - It is method for number which applicable for int and double.
// - Converts a number to a string representation with a fixed number of decimal places.

// Syntax
// variable.toStringAsFixed(precision digit);

// Note
// - This will return string.

// Example
void main() {
  num variableName = 99.126;
  print(variableName.toStringAsFixed(2));
}
