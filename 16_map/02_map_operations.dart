// Map Operations

// Example
void main() {
  var map1 = {"key1": "value1", "key2": "value2", "key3": "value3"};

  // Accessing Values
  print(map1["key1"]); // Output: value1

  // Adding a New Key-Value Pair
  map1["key4"] = "value4";
  print(map1);

  // Updating an Existing Value
  map1["key2"] = "updatedValue2";
  print(map1); 
}
