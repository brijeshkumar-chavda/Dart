// .values

// What
// - It returns an iterable containing all the values of the map.

// Syntax
// map.values;

// Example
void main() {
  Map<String, String> map1 = {
    "key1": "value1",
    "key2": "value2",
    "key3": "value3",
  };

  // Accessing Values
  print(map1.values); // Output: [value1, value2, value3]
}
