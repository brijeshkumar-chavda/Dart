// Set

// What
// - A Set is an unordered collection of unique items in Dart.
// - It does not allow duplicate values.

// Note
// - It does not maintain the order of elements.

// Example
void main() {
  // Set with explicit type
  Set<String> variable1 = {"element1", "element2", "element3"};
  print(variable1);

  // Set without explicit type
  var variable2 = {"element1", "element2", "element3"};
  print(variable2);
}
