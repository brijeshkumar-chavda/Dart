// Switch case statement

void main() {
  String caseType = "case 1";

  switch (caseType) {
    case "case 1":
      {
        print("I am case 1");
      }
      break;
    case "case 2":
      {
        print("I am case 2");
      }
      break;
    case "case 3":
      {
        print("I am case 3");
      }
      break;
    default:
      {
        print("I am default case");
      }
  }
}
