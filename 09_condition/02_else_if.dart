// else if condition statement

// What
// - if first condition is false then second condition which is else if will be evaluate.
// - if both condition are fail to evaluate then else block execute.

// Example
void main() {
  if (10 > 0) {
    print("if block executed");
  } else if (20 > 0) {
    print("if block executed");
  } else {
    print("else block executed");
  }
}
